-- Existing account-deletion path (20250203_delete_user_function.sql, applied on hosted).
create function public.delete_user() returns void language sql security definer set search_path = public as $$
  delete from auth.users where id = auth.uid();
$$;

-- Hosted conversations/messages (columns observed); used only as the source of
-- "the user's own message" authorization evidence.
create table public.conversations (
  id integer generated by default as identity primary key,
  conversation_identifier uuid not null default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text,
  created_at timestamptz default now()
);
alter table public.conversations enable row level security;
create policy "Users can view own conversations" on public.conversations
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Users can insert own conversations" on public.conversations
  for insert to authenticated with check ((select auth.uid()) = user_id);
create table public.messages (
  id integer generated by default as identity primary key,
  conversation_id integer not null references public.conversations(id) on delete cascade,
  role text not null,
  content text not null,
  created_at timestamptz default now()
);
alter table public.messages enable row level security;
create policy "Users can view own messages" on public.messages
  for select to authenticated using (conversation_id in (select id from public.conversations where user_id = (select auth.uid())));
create policy "Users can insert own messages" on public.messages
  for insert to authenticated with check (conversation_id in (select id from public.conversations where user_id = (select auth.uid())));
