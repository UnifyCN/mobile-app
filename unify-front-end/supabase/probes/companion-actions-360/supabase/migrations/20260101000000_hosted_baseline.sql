-- Hosted shape of the checklist tables as observed read-only on 2026-10-25
-- (shared hosted project). See DOCS/companion-actions/evidence/hosted-read-2026-10-25.md.
-- Probe fixture only. Columns, constraints, policies, triggers match the evidence.
-- Not modelled: columns of public.users and personalized_checklist_tasks beyond
-- what the checklist tables reference.

create table public.users (
  id uuid primary key references auth.users(id) on delete cascade
);
-- Hosted copies each new auth user into public.users; the probe does the same.
create function public.probe_handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.users (id) values (new.id) on conflict do nothing;
  return new;
end $$;
create trigger probe_on_auth_user_created after insert on auth.users
  for each row execute function public.probe_handle_new_user();

-- stage and priority are enum types on hosted ("USER-DEFINED"); text here, the probe never filters on them.
create table public.personalized_checklist_tasks (
  id integer generated by default as identity primary key,
  persona varchar,
  stage text,
  priority text,
  task_name varchar,
  task_description text,
  task_module varchar
);
alter table public.personalized_checklist_tasks enable row level security;
create policy "probe read all" on public.personalized_checklist_tasks for select to authenticated using (true);

create table public.user_tasks (
  user_task_id integer generated by default as identity primary key,
  user_id uuid references public.users(id) on delete cascade,
  task_id integer references public.personalized_checklist_tasks(id) on delete cascade,
  completed boolean default false,
  completed_at timestamp without time zone,
  sanity_checklist_id text,
  created_at timestamptz not null default now(),
  dismissed_at timestamptz,
  constraint user_tasks_user_sanity_checklist_id_key unique (user_id, sanity_checklist_id)
);
alter table public.user_tasks enable row level security;
-- Hosted has NO delete policy on user_tasks (observed).
create policy "Users can view own tasks" on public.user_tasks
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Users can insert own tasks" on public.user_tasks
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Users can update own tasks" on public.user_tasks
  for update to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

create table public.custom_checklist_tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  priority text not null check (priority in ('Do now', 'Do soon', 'Explore and connect', 'Optional / later')),
  title text not null,
  description text not null default '',
  completed boolean not null default false,
  completed_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);
alter table public.custom_checklist_tasks enable row level security;
create policy "Users can read own custom checklist tasks" on public.custom_checklist_tasks
  for select using (auth.uid() = user_id);
create policy "Users can insert own custom checklist tasks" on public.custom_checklist_tasks
  for insert with check (auth.uid() = user_id);
create policy "Users can update own custom checklist tasks" on public.custom_checklist_tasks
  for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users can delete own custom checklist tasks" on public.custom_checklist_tasks
  for delete using (auth.uid() = user_id);
create function public.set_updated_at_custom_checklist_tasks() returns trigger as $$
begin new.updated_at = timezone('utc', now()); return new; end;
$$ language plpgsql;
create trigger custom_checklist_tasks_updated_at before update on public.custom_checklist_tasks
  for each row execute function public.set_updated_at_custom_checklist_tasks();

create table public.checklist_task_order (
